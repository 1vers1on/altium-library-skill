# Widest glyph of each face, used for characters outside the tabulated range.
FALLBACK = {face: max(table) for face, table in WIDTHS.items()}

# FontID -> (face, size in points). These match the FileHeader font table the
# writer emits: 1 pin names and numbers, 2 unit titles, 3 group headings/notes.
FONTS = {1: ("times", 10), 2: ("arial_bold", 8), 3: ("arial", 6)}

# Fraction of the em treated as ink when testing for collisions. Uppercase cap
# height is about 0.66 em in both faces; 0.72 leaves a margin without making
# rows one pin pitch apart (1.0 em) appear to touch.
INK = 0.72


def size(font_id):
    return FONTS[font_id][1]


def width(text, font_id):
    """Advance width of `text` in 10 mil units."""
    face, points = FONTS[font_id]
    table = WIDTHS[face]
    fallback = FALLBACK[face]
    total = 0
    for ch in str(text):
        i = ord(ch) - FIRST
        total += table[i] if 0 <= i < len(table) else fallback
    return total * points / 1000.0


def box(text, font_id, x, y, anchor):
    """Ink box (x0,y0,x1,y1) in 10 mil units, y increasing downward.

    Anchors use the Pillow spelling the preview renderer draws with: first
    letter horizontal (l/m/r), second vertical (m centred, s baseline).
    """
    w = width(text, font_id)
    h = INK * size(font_id)
    x0 = {"l": x, "m": x - w / 2, "r": x - w}[anchor[0]]
    y0 = y - h / 2 if anchor[1] == "m" else y - h
    return (x0, y0, x0 + w, y0 + h)


def overlap(a, b, tolerance=0.25):
    """True when two ink boxes overlap by more than `tolerance` units on both axes."""
    return (min(a[2], b[2]) - max(a[0], b[0]) > tolerance) and (
        min(a[3], b[3]) - max(a[1], b[1]) > tolerance
    )
